function getPillarForCommand(cmdName) {
  const clean = String(cmdName || '').toLowerCase().replace(/^[!./#]/, '');
  return PILLAR_MAPPING[clean] || 'polaris';
}

function getCommandsByPillar(pillar) {
  return COMMANDS.filter((cmd) => getPillarForCommand(cmd.name) === pillar);
}

